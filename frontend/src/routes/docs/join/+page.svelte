<section>
  <h2>Get on the board</h2>
  <ol>
    <li>Open the link your host shared. It looks like <code>…/board/&lt;name&gt;</code>.</li>
    <li>Type a display name and click <strong>Join the retro</strong>. No account is needed, and your name is saved on this device for next time.</li>
    <li>Look at the phase strip at the top of the board. It shows where the retro is, and what you can do changes with it.</li>
  </ol>
</section>

<section>
  <h2>What each phase asks of you</h2>
  <ol>
    <li><strong>Brainstorm.</strong> Add cards to the columns. One thought per card, and don't worry about duplicates. This is the only phase where cards can be added to those columns.</li>
    <li><strong>Group.</strong> Help pull related cards together. See <a href="/docs/group">Group and merge cards</a>, or <a href="/docs/canvas">Use a canvas board</a> if your board is a canvas.</li>
    <li><strong>Vote.</strong> Click ▲ on the cards you most want to talk about, and click again to undo. There's no limit per person. Voting is only open in this phase.</li>
    <li><strong>Discuss.</strong> The team talks through the top votes. Use 💬 to add context and 😀 to react with any emoji.</li>
    <li><strong>Actions.</strong> Write concrete next steps in <em>Action items</em>. A name and a date beat "we should improve testing". Some boards have no Action items column, and those end at Discuss.</li>
  </ol>
</section>

<section>
  <h2>What you can do on a card</h2>
  <ul>
    <li><strong>React</strong> with 😀 and <strong>comment</strong> with 💬, in any phase.</li>
    <li><strong>Edit or delete your own card</strong> with the pencil and trash icons, in any phase.</li>
    <li><strong>Move a card</strong> by dragging it, or focus it and press <kbd>Shift</kbd>+arrow keys.</li>
  </ul>
</section>

<section>
  <h2>Good to know</h2>
  <ul>
    <li><strong>Anonymous boards.</strong> New boards start anonymous, shown by an <em>Anonymous</em> badge in the header. Names are hidden on cards and comments, but your name is still recorded, so treat it as a display setting and not a guarantee.</li>
    <li><strong>Hidden cards.</strong> Your host can hide cards during Brainstorm. You see your own, others show as placeholders, and they all appear when the board moves to Group.</li>
    <li><strong>Changing your name.</strong> Click your name in the header, or in the menu on a phone.</li>
    <li><strong>The timer.</strong> If your host starts one, it appears in the header for everyone.</li>
  </ul>
</section>
