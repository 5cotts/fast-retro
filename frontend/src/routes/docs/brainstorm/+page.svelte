<p>Use this when you want ideas on several questions without people influencing each other, for example: "Here are 5 problem statements. Generate ideas for 10 minutes, in private, then we'll reveal, group and discuss."</p>

<section>
  <h2>Set it up</h2>
  <ol>
    <li>On the homepage, click <strong>Start a new retro</strong> and pick <strong>Custom</strong> under <em>Board type</em>.</li>
    <li>Add one column per problem statement. Untick <em>Action items</em> if you don't want that column; the board then ends at Discuss.</li>
    <li>Tick <strong>Hide others' cards while brainstorming</strong>, then click <strong>Create retro</strong>.</li>
    <li>Click <strong>Share</strong> and send the link to your team.</li>
  </ol>
</section>

<section>
  <h2>Run it</h2>
  <ol>
    <li><strong>Brainstorm.</strong> Start the timer for 10 minutes. Everyone adds ideas to any column. They see their own cards, and other people's show as placeholders.</li>
    <li><strong>Reveal.</strong> Click <em>Next phase</em> to move to Group. Every card appears at once.</li>
    <li><strong>Group.</strong> The team pulls similar ideas together, across columns too. See <a href="/docs/group">Group and merge cards</a>.</li>
    <li><strong>Vote and discuss.</strong> Advance through Vote and Discuss, and talk through the top ideas.</li>
  </ol>
</section>

<section>
  <h2>Good to know</h2>
  <ul>
    <li><strong>Forgot something?</strong> Add a column or change <em>Hide cards</em> after creating the board. See <a href="/docs/setup">Set up and change a board</a>.</li>
    <li><strong>Hiding isn't security.</strong> It stops people being influenced by each other, but the board's data still reaches every browser.</li>
    <li><strong>Action items are never hidden.</strong></li>
  </ul>
</section>
