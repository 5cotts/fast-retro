<section>
  <h2>Save a copy</h2>
  <p class="mb-3">Hosts open the <strong>Export</strong> menu in the header. After a retro ends, anyone with its link can use the <strong>Export</strong> menu in the "This retro has ended" banner, with no name needed. The files are the same either way.</p>
  <ul>
    <li><strong>Save board file.</strong> A full <code>.fastretro.json</code> copy: cards in order, who voted and reacted, comments, the board's name, phase, columns and settings. Anonymous boards leave names out.</li>
    <li><strong>Spreadsheet (CSV).</strong> Card text, vote counts, reactions and comments for Sheets or Excel. It can't be imported back.</li>
  </ul>
</section>

<section>
  <h2>Import a board file</h2>
  <ol>
    <li>On the homepage, click <strong>Start a new retro</strong>, then <strong>Import from file…</strong>. You can also drop the file anywhere on the homepage.</li>
    <li>Check the preview, then click <strong>Import retro</strong>.</li>
  </ol>
  <p class="mt-3">You get a new board that looks the same, with votes, reactions, comments, phase and settings restored. Importing doesn't need Google sign-in. The board shows an <em>Imported from a file</em> note, since the file decides who voted and wrote what.</p>
</section>

<section>
  <h2>End a retro</h2>
  <p>The host clicks <strong>End retro</strong>, then <strong>Archive &amp; end</strong> or <strong>Save board file &amp; end</strong>. That saves a snapshot and makes the board read-only for everyone. If you're signed in, it stays under <em>My retros</em> on the homepage with an <em>Ended</em> tag.</p>
</section>

<section>
  <h2>Start the next retro</h2>
  <ol>
    <li>On the ended board, the host clicks <strong>Start next retro</strong>.</li>
    <li>You get a fresh board with the same name and columns, or the same canvas prompts.</li>
    <li>By default it brings this retro's action items along, without their votes or reactions, so the team can check on them. Untick <strong>Bring N action items</strong> for an empty board.</li>
  </ol>
</section>
